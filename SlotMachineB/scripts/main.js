// Old machines were entities. They are removed and dropped as the new item (plus the bet emeralds).
function migrateLegacy() {
    for (const id of ["minecraft:overworld", "minecraft:nether", "minecraft:the_end"]) {
        let dim;
        try {
            dim = world.getDimension(id);
        }
        catch {
            continue;
        }
        for (const old of dim.getEntities({ type: LEGACY_ID })) {
            const tag = old.getTags().find((t) => /^bet_[1-5]$/.test(t));
            const bet = tag ? Number(tag.slice(4)) : 0;
            give(dim, old.location, BLOCK_ID, 1);
            if (bet > 0)
                give(dim, old.location, "minecraft:emerald", bet);
            old.remove();
        }
    }
}
world.afterEvents.worldLoad.subscribe(() => {
    migrateLegacy();
    system.runInterval(() => { migrateLegacy(); }, 200);
    system.runInterval(watchdog, 40);
});
